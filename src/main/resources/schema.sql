CREATE TABLE IF NOT EXISTS campaigns (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 name VARCHAR(120) NOT NULL,
 channel VARCHAR(40) NOT NULL,
 cost DECIMAL(12,2) NOT NULL CHECK(cost >= 0)
);
CREATE TABLE IF NOT EXISTS leads (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 campaign_id BIGINT NOT NULL REFERENCES campaigns(id),
 name VARCHAR(120) NOT NULL,
 email VARCHAR(254) NOT NULL UNIQUE,
 phone VARCHAR(11) NOT NULL UNIQUE,
 status VARCHAR(20) NOT NULL CHECK(status IN ('NEW','CONVERTED')),
 revenue DECIMAL(12,2) NOT NULL DEFAULT 0,
 CONSTRAINT valid_conversion CHECK((status='NEW' AND revenue=0) OR (status='CONVERTED' AND revenue>0))
);
CREATE INDEX IF NOT EXISTS idx_leads_campaign ON leads(campaign_id,id);
